"""Independent DP history KV and an on-demand, freshly computed recent window.

All mutable video state lives on the history-cache object, including the
pre-language-model features. Existing even-prefix / odd-endpoint transactions
can therefore fork the complete state without leaking an odd padded unit.
Only original visual features move from recent to history. History never reads
recent KV, and recent prefill reads only the immutable common text prefix.
"""

from dataclasses import dataclass
import time

import torch
from transformers.cache_utils import DynamicCache

from sparsemm_baselines.core import BaselineConfig, _head_scores
from sparsemm_native.recent4 import Recent4StreamingQwen, allocate_recent4_budgets
from sparsemm_protokv.cache import StreamingCache
from sparsemm_protokv.streaming import StreamingQwen


@dataclass
class VisualUnit:
    features: torch.Tensor
    positions: torch.Tensor
    grid: tuple
    frame_start: int
    real_frames: int

    @property
    def tokens(self):
        return int(self.features.shape[1])


def dense_prefix(cache):
    """Freeze precisely the prefix generated by the existing streaming path."""
    return tuple((
        torch.stack([layer.get_segment(h)[0][:cache.prefix_tokens]
                     for h in range(cache.num_kv_heads)])[None].clone(),
        torch.stack([layer.get_segment(h)[1][:cache.prefix_tokens]
                     for h in range(cache.num_kv_heads)])[None].clone(),
    ) for layer in cache.layers)


@torch.inference_mode()
def prefill_recent(language_model, prefix, units):
    """One dense native forward, with prefix-only past and absolute positions."""
    if not 1 <= len(units) <= 2 or not prefix:
        raise ValueError("Recent rebuild requires one/two units and a common prefix")
    embeddings = torch.cat([unit.features for unit in units], dim=1)
    positions = torch.cat([unit.positions for unit in units], dim=2)
    prefix_tokens = int(prefix[0][0].shape[2])
    # Native DynamicLayer.update concatenates into new storage; prefix tensors
    # are never modified. This is a new cache object on every rebuild.
    recent = DynamicCache.from_legacy_cache(prefix)
    if recent.get_seq_length() != prefix_tokens:
        raise AssertionError("Recent prefill inherited non-prefix KV")
    result = language_model(
        inputs_embeds=embeddings, position_ids=positions, past_key_values=recent,
        cache_position=torch.arange(prefix_tokens, prefix_tokens + embeddings.shape[1],
                                    device=embeddings.device),
        attention_mask=torch.ones((1, prefix_tokens + embeddings.shape[1]),
                                  dtype=torch.long, device=embeddings.device),
        use_cache=True, return_dict=True,
    )
    recent = result.past_key_values
    if any(key.shape[2] != prefix_tokens + embeddings.shape[1] for key, _ in recent):
        raise AssertionError("Recent rebuild did not retain the entire window")
    return recent


class IndependentHistoryCache(StreamingCache):
    """Only text prefix and historical tokens can enter this attention cache."""

    def __init__(self, *args, history_weights, **kwargs):
        super().__init__(*args, **kwargs)
        self.history_weights = history_weights.detach().cpu().clone()
        if self.history_weights.shape != (self.num_layers, self.num_kv_heads):
            raise ValueError("History weights do not match model KV heads")
        self.units = []
        self.prefix_dense = None
        self.recent_dense = None
        self.recent_builds = 0
        self.recent_hits = 0
        self.history_units = 0
        self.revision = 0
        self.global_capacity_guard = False
        self.budgets = torch.full_like(self.history_weights, self.config.budget)
        self.recent_budgets = torch.full_like(self.budgets, self.config.window_size)
        self.history_budgets = self.budgets - self.recent_budgets
        self.allocation = dict(method="independent_history_recent_uninitialized")
        self.selector_seconds = 0.0
        self.timing_enabled = False
        self.score_config = BaselineConfig(
            method="adakv", budget=self.config.budget, window_size=self.config.window_size,
            kernel_size=self.config.kernel_size, pooling=self.config.pooling,
            gqa_reduce=self.config.gqa_reduce, budget_scope="visual", score_precision="float32")

    def push_unit(self, unit):
        if (unit.features.ndim != 3 or unit.features.shape[0] != 1
                or unit.positions.shape != (3, 1, unit.tokens) or unit.tokens < 1
                or not 1 <= unit.real_frames <= 2):
            raise ValueError("Invalid independent visual temporal unit")
        if self.units and unit.frame_start <= self.units[-1].frame_start:
            raise ValueError("Visual time must advance within a video branch")
        pending = self.units + [unit]
        outgoing = pending[0] if len(pending) > 2 else None
        self.units = pending[-2:]
        self.budgets, self.recent_budgets, self.allocation = allocate_recent4_budgets(
            self.history_weights, [item.tokens for item in self.units],
            self.config.budget, self.config.window_size)
        self.history_budgets = self.budgets - self.recent_budgets
        self.global_capacity_guard = False
        if outgoing is not None:
            # Some layers can bypass quotas while others retain above-mean
            # DP quotas. Predict that mixed-layer occupancy before mutation.
            predicted = 0
            r = int(self.recent_budgets[0, 0])
            for index, layer in enumerate(self.layers):
                candidates = [int(n) - self.prefix_tokens + outgoing.tokens for n in layer.head_lens.tolist()]
                warmup = self.config.sparsemm_two_bank_gate == "legacy_global" and all(n + r < self.config.budget for n in candidates)
                predicted += sum((n if warmup else min(n, int(self.history_budgets[index, h]))) + r
                                 for h, n in enumerate(candidates))
            self.global_capacity_guard = predicted > self.num_layers * self.num_kv_heads * self.config.budget
        self.allocation.update(
            representation="independent_history_and_fresh_recent_video_KV",
            recent_reads_history=False, history_reads_recent=False,
            transfer="original_visual_features_reencoded_by_history_branch",
            short_cache_gate=self.config.sparsemm_two_bank_gate,
            history_scoring_queries="history_branch_own_outgoing_unit_last32",
            global_capacity_guard=self.global_capacity_guard,
        )
        self.recent_dense = None
        self.revision += 1
        return outgoing

    @torch.inference_mode()
    def append_layer(self, layer_idx, k, v, raw_k=None, q=None):
        if self.phase != "video":
            return super().append_layer(layer_idx, k, v, raw_k=raw_k, q=q)
        if self._context_done or layer_idx in self._appended or q is None:
            raise RuntimeError("History requires one independent native forward per layer")
        expected = (1, self.num_kv_heads, self._positions.shape[1], self.head_dim)
        if k.shape != expected or v.shape != expected or q.shape[0] != 1 or q.shape[2:] != k.shape[2:]:
            raise ValueError("History K/V/Q shapes disagree")
        if not self.units or bool((self._positions[0] >= self.units[0].positions[0, 0].min()).any()):
            raise AssertionError("A recent token entered the history forward")
        layer = self.layers[layer_idx]
        layer.append_chunk(k, v, self._positions)
        before = layer.head_lens.tolist()
        r = int(self.recent_budgets[layer_idx, 0])
        # Equivalent global short-cache gate, with the independently stored
        # current recent window included when checking the visual occupancy.
        warmup = not self.global_capacity_guard and self.config.sparsemm_two_bank_gate == "legacy_global" and all(
            length - self.prefix_tokens + r < self.config.budget for length in before)
        started = time.perf_counter()
        keys = [layer.get_segment(h)[0] for h in range(self.num_kv_heads)]
        groups = q.shape[1] // self.num_kv_heads
        selected, counts = [], []
        for head, key in enumerate(keys):
            visual = int(key.shape[0]) - self.prefix_tokens
            capacity = int(self.history_budgets[layer_idx, head])
            keep_count = visual if warmup else min(visual, capacity)
            if keep_count == visual:
                keep = torch.arange(key.shape[0], device=key.device)
            else:
                if keep_count:
                    scores = _head_scores(key, q[0, head * groups:(head + 1) * groups],
                                          self.prefix_tokens, 0, self.score_config, layer_idx, head)
                    chosen = torch.sort(scores, descending=True).indices[:keep_count] + self.prefix_tokens
                else:
                    chosen = torch.empty(0, dtype=torch.long, device=key.device)
                keep = torch.cat((torch.arange(self.prefix_tokens, device=key.device), chosen))
            selected.append(keep.long())
            counts.append(keep_count)
        layer.prune(selected)
        after = layer.head_lens.tolist()
        if any(length != self.prefix_tokens + count for length, count in zip(after, counts)):
            raise AssertionError("History occupancy differs from independent quotas")
        if not warmup and any(count > int(self.history_budgets[layer_idx, head])
                              for head, count in enumerate(counts)):
            raise AssertionError("History exceeded its quota")
        if sum(counts) + self.num_kv_heads * r > self.num_kv_heads * self.config.budget:
            # Per-layer mean can exceed 500 because DP apportions globally.
            if warmup:
                raise AssertionError("Global warmup exceeded the mean budget")
        self.selector_seconds += time.perf_counter() - started
        self._pending_metadata[layer_idx] = dict(
            method="independent_history_attention", layer_idx=layer_idx,
            compressed=any(a < b for a, b in zip(after, before)),
            before_head_lengths=before, head_lengths=after,
            history_budgets=self.history_budgets[layer_idx].tolist(),
            retained_history_counts=counts, recent_tokens_not_visible=r,
            reference_warmup_bypass=warmup, observed_queries=min(q.shape[2], self.config.window_size),
            history_reads_recent=False, score_precision="float32",
            pooling=self.config.pooling, kernel_size=self.config.kernel_size,
            kept_indices=[indices.tolist() for indices in selected],
        )
        self._appended.add(layer_idx)

    def state_tensors(self):
        state = super().state_tensors()
        for index, unit in enumerate(self.units):
            state[f"recent_features.{index}"] = unit.features
            state[f"recent_positions.{index}"] = unit.positions
        if self.recent_dense is not None:
            for index, (k, v) in enumerate(self.recent_dense):
                state[f"recent_kv.{index}.k"] = k
                state[f"recent_kv.{index}.v"] = v
        return state

    def memory_stats(self):
        result = super().memory_stats()
        result["history_kv_bytes"] = self.nbytes()
        result["recent_feature_bytes"] = sum(unit.features.numel() * unit.features.element_size()
                                            for unit in self.units)
        result["recent_kv_bytes"] = (sum(t.numel() * t.element_size() for pair in self.recent_dense for t in pair)
                                     if self.recent_dense is not None else 0)
        result["extra_prefix_dense_bytes"] = (sum(t.numel() * t.element_size()
                                                   for pair in self.prefix_dense for t in pair)
                                              if self.prefix_dense is not None else 0)
        # Base memory_stats already counts the tensors exposed by our
        # state_tensors override, but classifies them as generic metadata.
        recent_positions = sum(unit.positions.numel() * unit.positions.element_size() for unit in self.units)
        result["metadata_bytes"] -= (result["recent_feature_bytes"] + result["recent_kv_bytes"]
                                     + recent_positions)
        result["recent_position_bytes"] = recent_positions
        result["persistent_kv_bytes"] += result["recent_kv_bytes"]
        result["persistent_total_bytes"] += result["extra_prefix_dense_bytes"]
        return result


def concatenate_query_cache(history, recent, logical_tokens):
    """Read-only layer/head assembly: one prefix + history + fresh recent KV."""
    fused = StreamingCache(history.config, history.num_layers, history.num_kv_heads,
                           history.head_dim, history.device, history.dtype)
    p = history.prefix_tokens
    recent_positions = torch.cat([unit.positions[:, 0] for unit in history.units], dim=1)
    r = int(recent_positions.shape[1])
    actual_history, actual_total = [], 0
    for index, layer in enumerate(history.layers):
        recent_k, recent_v = recent[index]
        if recent_k.shape[2] != p + r:
            raise AssertionError("The recent cache contains something outside its current window")
        keys, values, positions, lengths, retained = [], [], [], [], []
        for head in range(history.num_kv_heads):
            hk, hv = layer.get_segment(head)
            hp = layer.get_position_segment(head)
            if hp.shape[1] > p and bool((hp[0, p:] >= recent_positions[0].min()).any()):
                raise AssertionError("Historical and recent time ranges overlap")
            keys.append(torch.cat((hk, recent_k[0, head, p:])))
            values.append(torch.cat((hv, recent_v[0, head, p:])))
            positions.append(torch.cat((hp, recent_positions), dim=1))
            lengths.append(int(hk.shape[0]) + r)
            retained.append(int(hk.shape[0]) - p)
            actual_total += retained[-1] + r
        target = fused.layers[index]
        target.flat_k, target.flat_v = torch.cat(keys), torch.cat(values)
        target.flat_pos = torch.cat(positions, dim=1)
        target.head_lens = target.head_lens.new_tensor(lengths)
        target._refresh()
        actual_history.append(retained)
    if actual_total > history.num_layers * history.num_kv_heads * history.config.budget:
        raise AssertionError("The assembled visual cache exceeded mean K500")
    fused.prefix_tokens, fused.logical_tokens = p, int(logical_tokens)
    fused._initialized, fused._context_done = True, True
    fused.phase = "video"
    audit = dict(
        recent_tokens_per_head=r, actual_history_counts=actual_history,
        actual_visual_slots=actual_total,
        target_visual_slots=history.num_layers * history.num_kv_heads * history.config.budget,
        prefix_copies_in_query=1, history_recent_time_ranges_disjoint=True,
        recent_frame_starts=[unit.frame_start for unit in history.units],
        recent_real_frames=sum(unit.real_frames for unit in history.units),
        history_units=history.history_units,
    )
    return fused, audit


class DecoupledRecent4StreamingQwen(Recent4StreamingQwen):
    """Same weights/vision/RoPE/quotas/QA, independent KV construction paths."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.timings.update(recent_rebuild_seconds=0.0, fusion_seconds=0.0)

    def clear_cache(self):
        self.kv_cache = IndependentHistoryCache(
            self.config, self.num_layers, self.num_kv_heads, self.head_dim, self.device, self.dtype,
            history_weights=self._seed_budgets - self._seed_recent_budgets)
        self.visual_start_idx = 0
        self._next_position = self._seen_visual_tokens = self.total_processed_frames = 0
        self.last_encoded_frames = self._prefills = self._compressions = 0
        self.conv_history, self.last_metadata = [], []
        self.last_question_metrics = {}

    @torch.inference_mode()
    def encode_init_prompt(self):
        super().encode_init_prompt()
        self.kv_cache.prefix_dense = dense_prefix(self.kv_cache)

    @torch.inference_mode()
    def forward_chunk(self, inputs_embeds, positions, compress=True, **kwargs):
        # Do not call Recent4.forward_chunk: features entering history must not
        # advance the independent current-window allocation a second time.
        before = getattr(self.kv_cache, "selector_seconds", 0)
        result = StreamingQwen.forward_chunk(self, inputs_embeds, positions, compress=compress, **kwargs)
        self.timings["selector_seconds"] += getattr(self.kv_cache, "selector_seconds", 0) - before
        return result

    @torch.inference_mode()
    def encode_video_chunk(self, video_chunk, is_last_chunk=False):
        if video_chunk is None or video_chunk.shape[0] == 0:
            return
        for start in range(0, video_chunk.shape[0], 2):
            frames = video_chunk[start:start + 2]
            if frames.shape[-1] == 3:
                frames = frames.permute(0, 3, 1, 2)
            with self._measure("vision_seconds"):
                processor_kwargs = {}
                if self.video_max_pixels is not None:
                    processor_kwargs['size'] = {
                        "shortest_edge": self.processor.video_processor.size["shortest_edge"],
                        "longest_edge": self.video_max_pixels,
                    }
                inputs = self.processor(
                    text=[""], videos=frames, return_tensors="pt",
                    **processor_kwargs).to(self.device, self.dtype)
                grid = inputs["video_grid_thw"]
                features = self.model.get_video_features(inputs["pixel_values_videos"], grid)[0].unsqueeze(0)
            positions = self._video_positions(grid[0].tolist(), features.shape[1])
            unit = VisualUnit(features.detach(), positions.detach(), tuple(grid[0].tolist()),
                              self.total_processed_frames, int(frames.shape[0]))
            outgoing = self.kv_cache.push_unit(unit)
            if outgoing is not None:
                self.forward_chunk(outgoing.features, outgoing.positions, compress=True,
                                   time=outgoing.frame_start + outgoing.real_frames)
                self.kv_cache.history_units += 1
            self._seen_visual_tokens += unit.tokens
            self._next_position = max(self._next_position, int(positions.max()) + 1)
            self.total_processed_frames += unit.real_frames
            self.timings["raw_frames"] += unit.real_frames
            self.timings["visual_tokens"] += unit.tokens
            self.timings["video_prefills"] += int(outgoing is not None)
        self.last_encoded_frames = int(video_chunk.shape[0])

    @torch.inference_mode()
    def question_answering(self, input_text, max_new_tokens=16, temperature=0, repetition_penalty=1.1):
        history = self.kv_cache
        if not history.units or history.prefix_dense is None:
            raise RuntimeError("A video window and common prefix are required")
        with self._measure("recent_rebuild_seconds"):
            if history.recent_dense is None:
                torch.cuda.synchronize(self.device) if self.device.type == "cuda" else None
                start = time.perf_counter()
                history.recent_dense = prefill_recent(self.language_model, history.prefix_dense, history.units)
                torch.cuda.synchronize(self.device) if self.device.type == "cuda" else None
                rebuild_seconds = time.perf_counter() - start
                history.recent_builds += 1
                reused = False
            else:
                rebuild_seconds = 0.0
                history.recent_hits += 1
                reused = True
        with self._measure("fusion_seconds"):
            start = time.perf_counter()
            fused, audit = concatenate_query_cache(
                history, history.recent_dense, self.visual_start_idx + self._seen_visual_tokens)
            torch.cuda.synchronize(self.device) if self.device.type == "cuda" else None
            fusion_seconds = time.perf_counter() - start
        identities = {key: value.data_ptr() for key, value in history.state_tensors().items()}
        self.kv_cache = fused
        try:
            answer = StreamingQwen.question_answering(
                self, input_text, max_new_tokens=max_new_tokens, temperature=temperature,
                repetition_penalty=repetition_penalty)
        finally:
            self.kv_cache = history
            if identities != {key: value.data_ptr() for key, value in history.state_tensors().items()}:
                raise AssertionError("Question answering changed an independent persistent branch")
        self.last_question_metrics = dict(
            audit, recent_rebuild_seconds=rebuild_seconds, fusion_seconds=fusion_seconds,
            recent_reused=reused, recent_rebuilds=history.recent_builds,
            recent_prefill_initial_tokens=self.visual_start_idx,
            recent_prefill_initial_history_tokens=0, history_reads_recent=False,
            history_and_recent_unchanged_after_question=True,
            allocation=dict(history.allocation), memory=history.memory_stats())
        return answer


def load_model(model_path, config, **kwargs):
    from sparsemm_protokv.model_loader import load_pretrained
    from sparsemm_native.assets import asset_metadata
    dtype = kwargs.pop("dtype", "bfloat16")
    device = kwargs.pop("device", "cuda")
    model, processor = load_pretrained(model_path, device=device, dtype=dtype)
    return DecoupledRecent4StreamingQwen(model, processor, config,
                                       asset_metadata=asset_metadata(config.sparsemm_score_path or None), **kwargs)
